#!/usr/bin/env python3
"""Turn the raw preset frames into the shipped pictures.

Reads docs/screenshots/raw-preset-<key>.png (from tools/preset_thumbs.mjs) and writes
  docs/screenshots/preset-<key>.png   640x480, 256 colours — the README gallery
  src/presets/thumbs.js               320x240 data URIs — the in-game cards
  Element-Guide.html                  the preset tour's pictures, refreshed in place
Run tools/build_standalone.py again afterwards so the one-file build carries the cards.
"""
import base64
import io
import re
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SHOTS = ROOT / 'docs' / 'screenshots'

keys = []
order = re.findall(r"key: '([a-z-]+)'", (ROOT / 'src' / 'presets' / 'scenes.js').read_text())
uris = {}
for key in order:
    raw = SHOTS / f'raw-preset-{key}.png'
    if not raw.exists():
        raise SystemExit(f'missing {raw} — run tools/preset_thumbs.mjs first')
    img = Image.open(raw).convert('RGB')
    full = img.resize((640, 480), Image.LANCZOS).quantize(256, Image.MEDIANCUT, dither=Image.Dither.NONE)
    full.save(SHOTS / f'preset-{key}.png', optimize=True)
    small = img.resize((320, 240), Image.LANCZOS).quantize(256, Image.MEDIANCUT, dither=Image.Dither.NONE)
    buf = io.BytesIO()
    small.save(buf, 'PNG', optimize=True)
    uris[key] = 'data:image/png;base64,' + base64.b64encode(buf.getvalue()).decode()
    keys.append(key)
    raw.unlink()

lines = [
    '/**',
    ' * GENERATED by tools/preset_thumbs.mjs + tools/finish_thumbs.py — do not edit by hand.',
    ' * One small action-shot per preset, as data URIs so the one-file build carries them.',
    ' */',
    'export const THUMBS = {',
]
for key in keys:
    lines.append(f"  '{key}':")
    lines.append(f"    '{uris[key]}',")
lines.append('};')
(ROOT / 'src' / 'presets' / 'thumbs.js').write_text('\n'.join(lines) + '\n')
# Refresh the pictures embedded in the guide's preset tour (matched by alt name).
scenes = (ROOT / 'src' / 'presets' / 'scenes.js').read_text()
names = dict(re.findall(r"key: '([a-z-]+)',\s*\n\s*name: '([^']+)'", scenes))
guide_path = ROOT / 'Element-Guide.html'
guide = guide_path.read_text()
for key in keys:
    pat = re.compile(r'(<img src=")[^"]*(" alt="' + re.escape(names[key]) + '")')
    guide, n = pat.subn(lambda m: m.group(1) + uris[key] + m.group(2), guide)
    if n != 1:
        raise SystemExit(f'guide: expected exactly one picture for {names[key]}, found {n}')
guide_path.write_text(guide)

total = sum(len(u) for u in uris.values())
print(f'{len(keys)} thumbs, {total // 1024} KB of data URIs -> src/presets/thumbs.js + Element-Guide.html')
